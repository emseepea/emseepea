import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const filePattern = /^(\d{4})-(.+)\.(proposed|accepted|rejected|deprecated|superseded)\.md$/;
const currentStatuses = new Set(["proposed", "accepted"]);
const allowedOversight = new Set([
  "confirmed",
  "pending",
  "rejected",
  "rejected-pending-supersede",
]);

export async function generateCompendium(decisionsDirectory) {
  const entries = await readdir(decisionsDirectory, { withFileTypes: true });
  const decisions = [];
  const ids = new Set();

  for (const entry of entries) {
    if (!entry.isFile()) continue;
    const match = entry.name.match(filePattern);
    if (!match) continue;

    const [, number, slug, filenameStatus] = match;
    const id = `ADR-${number}`;
    if (ids.has(id)) throw new Error(`Duplicate decision ID: ${id}`);
    ids.add(id);

    const source = await readFile(path.join(decisionsDirectory, entry.name), "utf8");
    decisions.push(parseDecision({ entry: entry.name, filenameStatus, id, slug, source }));
  }

  decisions.sort((left, right) => left.id.localeCompare(right.id));
  const byId = new Map(decisions.map((decision) => [decision.id, decision]));

  for (const decision of decisions) {
    for (const relatedId of [...decision.supersedes, ...decision.explicitSupersededBy]) {
      if (!byId.has(relatedId)) {
        throw new Error(`${decision.id} refers to missing decision ${relatedId}`);
      }
    }
  }

  for (const decision of decisions) {
    decision.supersededBy = decisions
      .filter((candidate) => candidate.supersedes.includes(decision.id))
      .map(({ id }) => id);
    for (const explicitId of decision.explicitSupersededBy) {
      if (!decision.supersededBy.includes(explicitId)) decision.supersededBy.push(explicitId);
    }
    decision.supersededBy.sort();
  }

  const current = decisions.filter(({ status }) => currentStatuses.has(status));
  const historical = decisions.filter(({ status }) => !currentStatuses.has(status));

  return [
    "# Architecture Decisions",
    "",
    "<!-- Generated by `npm run decisions:generate`. Do not edit this file directly. -->",
    "",
    "Use the quick index to find a decision. The details below preserve each",
    "decision's chosen approach, its checks, and any decision it replaces.",
    "",
    `This project has ${decisions.length} decisions: ${current.length} current and ${historical.length} historical.`,
    "",
    "## Quick Index",
    "",
    ...renderIndex("Current decisions", current),
    "",
    ...renderIndex("Historical decisions", historical),
    "",
    "## Decision Details",
    "",
    ...decisions.flatMap((decision, index) => [
      ...(index === 0 ? [] : [""]),
      ...renderDecision(decision, byId),
    ]),
    "",
  ].join("\n");
}

function parseDecision({ entry, filenameStatus, id, source }) {
  const lines = source.split(/\r?\n/);
  if (lines[0] !== "---") throw new Error(`${id} has no leading frontmatter`);
  const frontmatterEnd = lines.indexOf("---", 1);
  if (frontmatterEnd < 0) throw new Error(`${id} has unclosed frontmatter`);

  const frontmatter = new Map();
  for (const line of lines.slice(1, frontmatterEnd)) {
    const match = line.match(/^([a-z][a-z-]*):\s*(.*)$/);
    if (match) frontmatter.set(match[1], match[2].trim());
  }

  const oversight = scalar(frontmatter.get("human-oversight"));
  if (!allowedOversight.has(oversight)) {
    throw new Error(`${id} has invalid human-oversight: ${oversight || "missing"}`);
  }

  const body = lines.slice(frontmatterEnd + 1);
  const title = body.find((line) => line.startsWith("# "))?.slice(2).trim();
  if (!title) throw new Error(`${id} has no title`);

  const outcomeLines = section(body, "Decision Outcome");
  const chosen = firstParagraph(outcomeLines, /^(Chosen option:|Chosen:)/);
  const confirmation = listItems(section(body, "Confirmation"));
  if (!chosen) throw new Error(`${id} has no chosen option in Decision Outcome`);
  if (confirmation.length === 0) throw new Error(`${id} has no Confirmation checks`);

  return {
    id,
    entry,
    title,
    status: filenameStatus,
    oversight,
    chosen,
    confirmation,
    supersedes: references(frontmatter.get("supersedes")),
    explicitSupersededBy: references(frontmatter.get("superseded-by")),
    supersededBy: [],
  };
}

function section(lines, heading) {
  const start = lines.findIndex((line) => line === `## ${heading}`);
  if (start < 0) return [];
  const rest = lines.slice(start + 1);
  const end = rest.findIndex((line) => line.startsWith("## "));
  return end < 0 ? rest : rest.slice(0, end);
}

function firstParagraph(lines, startPattern) {
  const start = lines.findIndex((line) => startPattern.test(line.trim()));
  if (start < 0) return "";
  const paragraph = [];
  for (const line of lines.slice(start)) {
    if (paragraph.length > 0 && line.trim() === "") break;
    if (line.trim()) paragraph.push(line.trim());
  }
  return paragraph.join(" ");
}

function listItems(lines) {
  const items = [];
  for (const line of lines) {
    const item = line.match(/^-\s+(.+)$/);
    if (item) {
      items.push(item[1].trim());
    } else if (items.length > 0 && /^\s+\S/.test(line)) {
      items[items.length - 1] += ` ${line.trim()}`;
    }
  }
  return items;
}

function scalar(value = "") {
  return value.replace(/^(["'])(.*)\1$/, "$2").trim();
}

function references(value = "") {
  return [...value.matchAll(/ADR-\d{4}/g)].map(([reference]) => reference);
}

function renderIndex(title, decisions) {
  return [
    `### ${title}`,
    "",
    ...(decisions.length === 0
      ? ["No decisions in this group."]
      : decisions.map(
          (decision) =>
            `- [${decision.id}: ${decision.title}](${decision.entry}): ${label(decision.status)}; human review ${label(decision.oversight).toLowerCase()}.`,
        )),
  ];
}

function renderDecision(decision, byId) {
  const lines = [
    `### [${decision.id}: ${decision.title}](${decision.entry})`,
    "",
    `- Status: ${label(decision.status)}`,
    `- Human review: ${label(decision.oversight)}`,
  ];

  if (decision.supersedes.length > 0) {
    lines.push(`- Replaces: ${linkedReferences(decision.supersedes, byId)}`);
  }
  if (decision.supersededBy.length > 0) {
    lines.push(`- Replaced by: ${linkedReferences(decision.supersededBy, byId)}`);
  }

  lines.push("", "#### Decision", "", decision.chosen, "", "#### How We Check It", "");
  lines.push(...decision.confirmation.map((check) => `- ${check}`));
  return lines;
}

function linkedReferences(ids, byId) {
  return ids
    .map((id) => {
      const decision = byId.get(id);
      return `[${id}: ${decision.title}](${decision.entry})`;
    })
    .join(", ");
}

function label(value) {
  return value
    .split("-")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(" ");
}

async function main() {
  const args = process.argv.slice(2);
  const check = args[0] === "--check";
  const directoryArgument = args[check ? 1 : 0] ?? "docs/decisions";
  const decisionsDirectory = path.resolve(directoryArgument);
  const target = path.join(decisionsDirectory, "README.md");
  const generated = await generateCompendium(decisionsDirectory);

  if (check) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== generated) throw new Error(`${target} is out of date; run npm run decisions:generate`);
    return;
  }

  await writeFile(target, generated);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error.message);
    process.exitCode = 1;
  });
}
